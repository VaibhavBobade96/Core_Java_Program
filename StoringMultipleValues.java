class StoringMultipleValues 
{
	public static void main(String[] args) 
	{
		int i1 = 10;
		int i2 = 20;
		int i3 = 30;
		int i4 = 40;
		int i5 = 50;
		
		System.out.println("i1 :" +i1);
		System.out.println("i2 :" +i2);
		System.out.println("i3 :" +i3);
		System.out.println("i4 :" +i4);
		System.out.println("i5 :" +i5);
	}
}
